#!/usr/bin/env python3
"""rtl/platform/alveo_xrt/bw/gen_bw.py — generate the M0 bandwidth kernel top, its kernel.xml and the
testbench wrapper (docs/m0-bw.md §4).

    rtl/platform/alveo_xrt/bw/gen_bw.py           write the files below
    rtl/platform/alveo_xrt/bw/gen_bw.py --check   exit 1 if a generated file is missing or stale

Kernel `tsr_bw_k4` (module name = kernel name): tsr_bw_kernel with NUM_CH 4, ADDR_BEAT_W 28
(16 GiB per channel), AXI_SLICES 2, CTRL_PIPE 2. Ports: ap_clk, ap_rst_n, interrupt,
s_axi_control (AXI4-Lite, 32-bit data, 12-bit address), m_axi_ch0..3 (AXI4, 512-bit data, 64-bit
address, 4-bit ID; the signal list of the Tesseract kernels, taken from ../gen_tops.py).

Outputs:
    rtl/platform/alveo_xrt/bw/tsr_bw_k4.v        named-port Verilog-2001 top around tsr_bw_kernel
    rtl/platform/alveo_xrt/bw/kernel_bw_k4.xml   Vitis kernel description (args = docs/m0-bw.md §2,
                                                 control range 0x1000, ap_ctrl_hs, interrupt)
    tb/platform/bw/sv/kwrap_tsr_bw_k4.sv         simulation wrapper: the named top with the packed
                                                 port list of tsr_bw_kernel (the bench drives both)
"""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[3]
TBSV = REPO / "tb" / "platform" / "bw" / "sv"

_spec = importlib.util.spec_from_file_location("tsr_gen_tops", HERE.parent / "gen_tops.py")
_gt = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_gt)
AXI = _gt.AXI                                   # the m_axi signal list (shared with tsr_u200_k*)

NAME = "tsr_bw_k4"
NUM_CH = 4
PARAMS = dict(NUM_CH=NUM_CH, ADDR_BEAT_W=28, AXI_SLICES=2, CTRL_PIPE=2)
AXIL = [
    ("awvalid", "in", 1), ("awready", "out", 1), ("awaddr", "in", 12),
    ("wvalid", "in", 1), ("wready", "out", 1), ("wdata", "in", 32), ("wstrb", "in", 4),
    ("bvalid", "out", 1), ("bready", "in", 1), ("bresp", "out", 2),
    ("arvalid", "in", 1), ("arready", "out", 1), ("araddr", "in", 12),
    ("rvalid", "out", 1), ("rready", "in", 1), ("rdata", "out", 32), ("rresp", "out", 2),
]

# Kernel arguments (docs/m0-bw.md §2): (name, address qualifier, port, size, offset, type)
ARGS = [("seed", 0, "s_axi_control", 4, 0x010, "uint")]
for _c in range(NUM_CH):
    _b = 0x020 + 0x20 * _c
    ARGS += [("ctrl%d" % _c, 0, "s_axi_control", 4, _b, "uint"),
             ("bytes%d" % _c, 0, "s_axi_control", 8, _b + 0x08, "ulong"),
             ("rd_off%d" % _c, 0, "s_axi_control", 8, _b + 0x10, "ulong"),
             ("wr_off%d" % _c, 0, "s_axi_control", 8, _b + 0x18, "ulong")]
ARGS += [("ch%d" % _c, 1, "m_axi_ch%d" % _c, 8, 0x0A0 + 8 * _c, "void*") for _c in range(NUM_CH)]


def _vw(n: int) -> str:
    return "" if n == 1 else "[%d:0]" % (n - 1)


def _join_ports(ports) -> str:
    out = []
    for i, p in enumerate(ports):
        last = i == len(ports) - 1
        if "lint_on SYMRSVDWORD" in p:
            a, b = p.rsplit("\n", 1)
            out.append(a + ("" if last else ",") + "\n" + b)
        else:
            out.append(p + ("" if last else ","))
    return "\n".join(out)


def gen_top() -> str:
    C = NUM_CH
    L = ["// %s.v — GENERATED by rtl/platform/alveo_xrt/bw/gen_bw.py; do not edit." % NAME,
         "//",
         "// Vitis RTL kernel `%s` (module name = kernel name): the M0 DMA bandwidth kernel," % NAME,
         "// tsr_bw_kernel with %s." % ", ".join("%s %s" % kv for kv in PARAMS.items()),
         "// Ports: ap_clk, ap_rst_n (active low, synchronous), interrupt, s_axi_control (AXI4-Lite, 32-bit",
         "// data, 12-bit address), m_axi_ch<c> for c < %d (AXI4, 512-bit data, 64-bit address, 4-bit ID)." % C,
         "// Register map and use: docs/m0-bw.md; kernel_bw_k4.xml describes the args.",
         "// Plain Verilog-2001 (the IP packager expects a Verilog top); the body is SystemVerilog.",
         "",
         "`default_nettype none",
         "",
         "module %s (" % NAME]
    ports = ["  input  wire          ap_clk", "  input  wire          ap_rst_n",
             "  // Vitis names the interrupt port `interrupt`, a C++ keyword for Verilator's model\n"
             "  /* verilator lint_off SYMRSVDWORD */\n"
             "  output wire          interrupt\n"
             "  /* verilator lint_on SYMRSVDWORD */"]
    for s_, d, w in AXIL:
        ports.append("  %-6s wire %-8s s_axi_control_%s" % ("input" if d == "in" else "output", _vw(w), s_))
    for c in range(C):
        for s_, d, w in AXI:
            ports.append("  %-6s wire %-8s m_axi_ch%d_%s" % ("input" if d == "in" else "output", _vw(w), c, s_))
    L.append(_join_ports(ports))
    L.append(");")
    L.append("")
    L.append("  // per-channel signals packed as tsr_bw_kernel's [NUM_CH][W] ports (channel c = bits [c*W +: W])")
    for s_, d, w in AXI:
        L.append("  wire [%d:0] %s;" % (C * w - 1, s_))
    L.append("")
    for s_, d, w in AXI:
        for c in range(C):
            if d == "out":
                L.append("  assign m_axi_ch%d_%s = %s[%d +: %d];" % (c, s_, s_, c * w, w))
            else:
                L.append("  assign %s[%d +: %d] = m_axi_ch%d_%s;" % (s_, c * w, w, c, s_))
    L.append("")
    L.append("  tsr_bw_kernel #(")
    L.append(",\n".join("    .%s(%s)" % (p, v) for p, v in PARAMS.items()))
    L.append("  ) u_kernel (")
    conns = ["    .ap_clk(ap_clk)", "    .ap_rst_n(ap_rst_n)", "    .interrupt(interrupt)"]
    conns += ["    .s_axi_control_%s(s_axi_control_%s)" % (s_, s_) for s_, _, _ in AXIL]
    conns += ["    .m_axi_%s(%s)" % (s_, s_) for s_, _, _ in AXI]
    L.append(",\n".join(conns))
    L.append("  );")
    L.append("")
    L.append("endmodule")
    L.append("")
    L.append("`default_nettype wire")
    return "\n".join(L) + "\n"


def gen_wrap() -> str:
    C = NUM_CH
    L = ["// kwrap_%s.sv — GENERATED by rtl/platform/alveo_xrt/bw/gen_bw.py; do not edit." % NAME,
         "//",
         "// Testbench-only wrapper: the packaged kernel %s with the packed port list of" % NAME,
         "// tsr_bw_kernel (NUM_CH = %d), so the same C++ bench (tb/platform/bw) drives the body and" % C,
         "// the named top. Not a synthesis source.",
         "",
         "module kwrap_%s #(" % NAME,
         "  parameter int unsigned NUM_CH = %d   // fixed by the kernel; present for the bench" % C,
         ") ("]
    ports = ["  input  logic        ap_clk", "  input  logic        ap_rst_n",
             "  /* verilator lint_off SYMRSVDWORD */\n  output logic        interrupt\n  /* verilator lint_on SYMRSVDWORD */"]
    for s, d, w in AXIL:
        ports.append("  %s %-8s s_axi_control_%s" % ("input  logic" if d == "in" else "output logic", _vw(w), s))
    for s, d, w in AXI:
        ports.append("  %s [NUM_CH-1:0]%s m_axi_%s" % ("input  logic" if d == "in" else "output logic",
                                                    "" if w == 1 else "[%d:0]" % (w - 1), s))
    L.append(_join_ports(ports))
    L.append(");")
    L.append("")
    L.append("  if (NUM_CH != %d) begin : g_chk_ch" % C)
    L.append("    $fatal(1, \"kwrap_%s: NUM_CH is %d\");" % (NAME, C))
    L.append("  end")
    L.append("")
    L.append("  %s u_top (" % NAME)
    conns = ["    .ap_clk", "    .ap_rst_n", "    .interrupt"]
    conns += ["    .s_axi_control_%s" % s for s, _, _ in AXIL]
    for c in range(C):
        conns += ["    .m_axi_ch%d_%s(m_axi_%s[%d])" % (c, s, s, c) for s, _, _ in AXI]
    L.append(",\n".join(conns))
    L.append("  );")
    L.append("")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def gen_xml() -> str:
    L = ['<?xml version="1.0" encoding="UTF-8"?>',
         '<!-- kernel_bw_k4.xml — GENERATED by rtl/platform/alveo_xrt/bw/gen_bw.py; do not edit.',
         '     Vitis RTL kernel %s (M0 DMA bandwidth kernel): s_axi_control register map =' % NAME,
         '     docs/m0-bw.md §2. The result registers at 0x0F0 .. 0x1FF have no args (read with',
         '     xrt::kernel::read_register after the run). -->',
         '<root versionMajor="1" versionMinor="6">',
         '  <kernel name="%s" language="ip_c" vlnv="tesseract:kernel:%s:1.0" attributes="" '
         'preferredWorkGroupSizeMultiple="0" workGroupSize="1" interrupt="true" hwControlProtocol="ap_ctrl_hs">'
         % (NAME, NAME),
         '    <ports>',
         '      <port name="s_axi_control" mode="slave" range="0x1000" dataWidth="32" portType="addressable" base="0x0"/>']
    for c in range(NUM_CH):
        L.append('      <port name="m_axi_ch%d" mode="master" range="0xFFFFFFFFFFFFFFFF" dataWidth="512" '
                 'portType="addressable" base="0x0"/>' % c)
    L.append('    </ports>')
    L.append('    <args>')
    for i, (n, aq, port, size, off, ty) in enumerate(ARGS):
        L.append('      <arg name="%s" addressQualifier="%d" id="%d" port="%s" size="0x%x" offset="0x%03X" '
                 'type="%s" hostOffset="0x0" hostSize="0x%x"/>' % (n, aq, i, port, size, off, ty, size))
    L.append('    </args>')
    L.append('  </kernel>')
    L.append('</root>')
    return "\n".join(L) + "\n"


def outputs() -> dict:
    return {HERE / ("%s.v" % NAME): gen_top(),
            HERE / "kernel_bw_k4.xml": gen_xml(),
            TBSV / ("kwrap_%s.sv" % NAME): gen_wrap()}


def main(argv) -> int:
    check = "--check" in argv
    bad = 0
    for path, text in outputs().items():
        if check:
            if not path.is_file() or path.read_text() != text:
                print("gen_bw.py: %s is missing or stale (run rtl/platform/alveo_xrt/bw/gen_bw.py)" % path)
                bad += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.is_file() or path.read_text() != text:
                path.write_text(text)
                print("wrote %s" % path.relative_to(REPO))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
